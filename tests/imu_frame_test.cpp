#include "imu_frame.h"
#include <cassert>
#include <cstdint>

int main()
{
    // HiPNUC HI91 手册中的完整 82 字节样例帧，数据域长度 0x004C，CRC 为 0xBB14。
    uint8_t frame[] = {
        0x5A, 0xA5, 0x4C, 0x00, 0x14, 0xBB, 0x91, 0x08, 0x15, 0x23,
        0x09, 0xA2, 0xC4, 0x47, 0x08, 0x15, 0x1C, 0x00, 0xCC, 0xE8,
        0x61, 0xBE, 0x9A, 0x35, 0x56, 0x3E, 0x65, 0xEA, 0x72, 0x3F,
        0x31, 0xD0, 0x7C, 0xBD, 0x75, 0xDD, 0xC5, 0xBB, 0x6B, 0xD7,
        0x24, 0xBC,
        0x89, 0x88, 0xFC, 0x40, 0x01, 0x00, 0x6A, 0x41, 0xAB, 0x2A,
        0x70, 0xC2, 0x96, 0xD4, 0x50, 0x41, 0xED, 0x03, 0x43, 0x41,
        0x41, 0xF4, 0xF4, 0xC2, 0xCC, 0xCA, 0xF8, 0xBE, 0x73, 0x6A,
        0x19, 0xBE, 0xF0, 0x00, 0x1C, 0x3D, 0x8D, 0x37, 0x5C, 0x3F
    };
    static_assert(sizeof(frame) == 82, "HI91 sample length");
    assert(ImuFrameValid(frame, sizeof(frame)));
    frame[20] ^= 1;
    assert(!ImuFrameValid(frame, sizeof(frame)));
    frame[20] ^= 1;
    assert(!ImuFrameValid(frame, 40));
    frame[2] = 0xFF;
    assert(!ImuFrameValid(frame, sizeof(frame)));
}
